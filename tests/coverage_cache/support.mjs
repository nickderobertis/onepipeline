const FIXTURE_BINARIES = new Set(["rest_fixture", "contract", "package_bundle", "e2e", "note", "codex_server", "pooled_slot", "narrow_write"]);

function fixtureLib(uncovered) {
  const functions = [...new Set(Object.values(FIXTURE_TESTS).flat().map(([fn]) => fn))];
  const padding = Array.from({ length: 400 }, (_, i) => `    v += ${i % 7};`).join("\n");
  const pad = `pub fn pad(mut v: u64) -> u64 {\n${padding}\n    v += 1;\n    v\n}\n`;
  const each = functions.map((fn) => `pub fn ${fn}() -> u64 {\n    pad(1)\n}\n`).join("");
  const uncoveredBody = Array.from({ length: uncovered }, (_, i) => `    v += ${i % 3};`).join("\n");
  return `${each}${pad}pub fn never(mut v: u64) -> u64 {\n${uncoveredBody}\n    v += 1;\n    v\n}\n`;
}

function testBody(entries) {
  const rendered = entries.map(([fn, name]) => {
    const [mod, leaf] = name.includes("::") ? name.split("::") : [null, name];
    const test = `#[test]\nfn ${leaf}() {\n    assert!(onepipeline::${fn}() > 0);\n}\n`;
    return mod ? `mod ${mod} {\n${test}}\n` : test;
  });
  return rendered.join("");
}

function manifest(version, stubs) {
  const test = (name, path) => `[[test]]\nname = "${name}"\npath = "${path}"\n`;
  const entries = [
    ...stubs.map((name) => [name, `tests/fixture_stubs/${name}.rs`]),
    ["rest_fixture", "tests/rest_fixture.rs"],
    ["contract", "tests/contract.rs"],
    ["package_bundle", "tests/package_bundle.rs"],
    ["e2e", "tests/e2e/main.rs"],
    ["note", "tests/note/main.rs"],
    ["codex_server", "tests/codex_server/main.rs"],
    ["pooled_slot", "tests/pooled_slot/main.rs"],
    ["narrow_write", "tests/narrow_write/main.rs"],
  ];
  return `[package]\nname = "onepipeline"\nversion = "${version}"\nedition = "2021"\nautotests = false\nautobins = false\nautoexamples = false\nautobenches = false\n\n[lib]\npath = "src/lib.rs"\n\n${entries.map(([n, p]) => test(n, p)).join("\n")}`;
}

const lockFor = (version) =>
  `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "onepipeline"\nversion = "${version}"\n`;

export function git(cwd, ...args) {
  return execFileSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, ...GIT_ENV }, stdio: ["ignore", "pipe", "pipe"] }).trim();
}

export function realVersion() {
  return readFileSync(join(root, "Cargo.toml"), "utf8").match(/\[package\][\s\S]*?\nversion = "([^"]+)"/)[1];
}

/**
 * Copy the working tree (tracked and new files) into a fresh repository and replace the Rust
 * code with the fixture crate. `uncovered` sets how many of the fixture's lines no tier reaches.
 */
export function scratch(t, { uncovered = 6 } = {}) {
  const dir = mkdtempSync(join(stateRoot(), "coverage-cache-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const files = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
    .split("\0")
    .filter((path) => path && existsSync(join(root, path)));
  for (const path of files) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    cpSync(join(root, path), join(dir, path), { verbatimSymlinks: true });
  }
  for (const modules of ["node_modules", ".github/node_modules"]) {
    if (existsSync(join(root, modules))) symlinkSync(join(root, modules), join(dir, modules));
  }
  const version = realVersion();
  // Every test binary nextest's config or a tier's filter names must exist, or nextest refuses.
  const stubs = [
    ...new Set(
      [readFileSync(join(dir, ".config/nextest.toml"), "utf8"), readFileSync(join(dir, "justfile"), "utf8")]
        .join("\n")
        .matchAll(/binary\((\w+)\)/g)
        .map(([, name]) => name),
    ),
  ].filter((name) => !FIXTURE_BINARIES.has(name));
  mkdirSync(join(dir, "tests/fixture_stubs"), { recursive: true });
  for (const name of stubs) writeFileSync(join(dir, `tests/fixture_stubs/${name}.rs`), "");
  writeFileSync(join(dir, "src/lib.rs"), fixtureLib(uncovered));
  for (const [path, entries] of Object.entries(FIXTURE_TESTS)) writeFileSync(join(dir, path), testBody(entries));
  writeFileSync(join(dir, "Cargo.toml"), manifest(version, stubs));
  writeFileSync(join(dir, "Cargo.lock"), lockFor(version));
  // What `_onetaskgraph-preflight` looks for, so the e2e tier's preflight passes offline.
  const onetaskgraph = readFileSync(join(dir, "justfile"), "utf8").match(/^onetaskgraph-version := "([^"]+)"/m)[1];
  const tool = join(dir, "target", "tools", `onetaskgraph-${onetaskgraph}`, "bin", "onetaskgraph");
  mkdirSync(dirname(tool), { recursive: true });
  writeFileSync(tool, "#!/bin/sh\nexit 0\n");
  chmodSync(tool, 0o755);
  git(dir, "init", "--quiet", "--initial-branch=main");
  git(dir, "add", "-A");
  git(dir, "commit", "--quiet", "--no-verify", "-m", "scratch");
  return dir;
}

const ANSI = /\u001b\[[0-9;]*[A-Za-z]/g;

/** Run a real Nx target and read what Nx's own run summary says about every task. */
export function nx(dir, args, { env = {}, path = [] } = {}) {
  const result = spawnSync("bash", ["scripts/nx.sh", ...args, "--outputStyle=static", "--skipRemoteCache"], {
    cwd: dir,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    env: {
      ...process.env,
      NX_DAEMON: "false",
      NX_TUI: "false",
      ONEPIPELINE_NX_SHOW_OUTPUT: "1",
      ...env,
      PATH: [...path, process.env.PATH].join(":"),
    },
  });
  const output = `${result.stdout}\n${result.stderr}`.replace(ANSI, "");
  const replayed = new Set();
  const executed = new Set();
  for (const line of output.split("\n")) {
    const match = line.match(/^\s*> nx run (\S+?)(\s+\[(.*)\])?\s*$/);
    if (!match) continue;
    const task = match[1];
    if (match[3] && /cache/.test(match[3])) replayed.add(task);
    else executed.add(task);
  }
  for (const task of replayed) executed.delete(task);
  return { status: result.status, output, replayed, executed };
}

